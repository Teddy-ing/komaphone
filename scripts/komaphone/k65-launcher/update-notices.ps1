# Regenerate the standalone launcher's notices from its locked local Cargo sources.
[CmdletBinding()]
param([string] $CargoExe)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$repository = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '../../..')).Path
. (Join-Path $PSScriptRoot 'build-environment.ps1')
$cargoEnv = Resolve-K65CargoEnvironment -WorkspaceRoot $repository -CargoExe $CargoExe
$metadata = $null
Invoke-K65BuildEnvironment -Variables $cargoEnv.Variables -Body {
    $raw = & $cargoEnv.CargoExe metadata --manifest-path (Join-Path $PSScriptRoot 'Cargo.toml') --locked --offline --format-version 1
    if ($LASTEXITCODE -ne 0) { throw 'Could not resolve the exact locked launcher dependency graph.' }
    $script:metadata = ($raw -join "`n") | ConvertFrom-Json
}
$lockHash = (Get-FileHash -LiteralPath (Join-Path $PSScriptRoot 'Cargo.lock') -Algorithm SHA256).Hash
$text = [Text.StringBuilder]::new()
[void]$text.AppendLine('Komaphone K6.5 launcher third-party notices')
[void]$text.AppendLine("Cargo.lock SHA256: $lockHash")
[void]$text.AppendLine('Generated by update-notices.ps1 from the exact offline Cargo dependency graph, including optional/build-only entries.')
[void]$text.AppendLine('Launcher source is MIT OR Apache-2.0; upstream application attribution remains in candidate/.')
$rows = [Collections.Generic.List[object]]::new()
foreach ($package in $metadata.packages | Where-Object { $null -ne $_.source } | Sort-Object name,version) {
    $root = [IO.Path]::GetDirectoryName($package.manifest_path)
    $licenses = @(Get-ChildItem -LiteralPath $root -File | Where-Object { $_.Name -match '^(LICENSE|LICENCE|COPYING|NOTICE)' } | Sort-Object Name)
    if (-not $licenses.Count) { throw "No original license texts found for $($package.name) $($package.version)." }
    foreach ($license in $licenses) {
        if ($license.Length -gt 1048576 -or $license.Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'License input must be a bounded regular file.' }
        [void]$text.AppendLine()
        [void]$text.AppendLine("=== $($package.name) $($package.version) / $($license.Name) / $($package.license) ===")
        [void]$text.AppendLine([IO.File]::ReadAllText($license.FullName))
        $rows.Add(@{name=$package.name;version=$package.version;file=$license.Name;sha256=(Get-FileHash -LiteralPath $license.FullName -Algorithm SHA256).Hash})
    }
}
$output = Join-Path $PSScriptRoot 'THIRD-PARTY-NOTICES.txt'
[IO.File]::WriteAllText($output,$text.ToString(),[Text.UTF8Encoding]::new($false))
[pscustomobject]@{output=$output;sha256=(Get-FileHash -LiteralPath $output -Algorithm SHA256).Hash;cargoLockSha256=$lockHash;licenseFiles=$rows.Count;licenses=$rows}
